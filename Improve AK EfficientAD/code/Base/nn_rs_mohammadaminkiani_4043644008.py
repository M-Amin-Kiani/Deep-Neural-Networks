def download(url, out_path: Path):
    tmp = out_path.with_suffix(out_path.suffix + ".tmp")
    if tmp.exists(): tmp.unlink()
    try:
        sh(f"aria2c -x 16 -s 16 -k 1M --file-allocation=none --max-tries=10 --retry-wait=3 "
           f"--user-agent='{UA}' -o '{tmp.name}' -d '{tmp.parent}' '{url}'")
    except subprocess.CalledProcessError:
        sh(f"curl -L --fail --retry 10 --retry-all-errors --retry-delay 3 -A '{UA}' -o '{tmp}' '{url}'")
    tmp.replace(out_path)
    sh(f"ls -lh '{out_path}'")


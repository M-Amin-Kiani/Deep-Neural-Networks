def _load_mask(mask_path: Path, target_shape):
    if mask_path.exists():
        m = np.array(Image.open(mask_path).convert("L"), dtype=np.uint8)
        m = (m > 0).astype(np.uint8)
        if m.shape != target_shape:
            m_img = Image.fromarray(m * 255).resize((target_shape[1], target_shape[0]), resample=Image.NEAREST)
            m = (np.array(m_img) > 0).astype(np.uint8)
        return m
    return np.zeros(target_shape, dtype=np.uint8)

def iter_samples(dataset_root: Path, anomaly_maps_root: Path, subdataset: str):
    """Yield (pred_map, gt_mask) one by one to keep RAM low."""
    test_dir = dataset_root / subdataset / "test"
    gt_dir = dataset_root / subdataset / "ground_truth"

    for defect in sorted([p.name for p in test_dir.iterdir() if p.is_dir()]):
        img_dir = test_dir / defect
        for img_path in sorted(img_dir.glob("*.*")):
            stem = img_path.stem
            pred_path = anomaly_maps_root / defect / f"{stem}.tiff"
            if not pred_path.exists():
                alt = anomaly_maps_root / defect / f"{stem}.tif"
                if alt.exists():
                    pred_path = alt
                else:
                    continue

            pred = tifffile.imread(pred_path.as_posix()).astype(np.float32)
            if pred.ndim != 2:
                pred = pred.squeeze()

            if defect == "good":
                gt = np.zeros(pred.shape, dtype=np.uint8)
            else:
                mask_path = gt_dir / defect / f"{stem}_mask.png"
                gt = _load_mask(mask_path, pred.shape)

            yield pred, gt, defect

def pixel_auroc_streaming(dataset_root: Path, anomaly_maps_root: Path, subdataset: str,
                          max_pixels=2_000_000, seed=42):
    """
    Compute Pixel AUROC with random pixel sampling to avoid huge RAM.
    max_pixels: maximum total pixels sampled across the dataset.
    """
    rng = np.random.default_rng(seed)
    y_true_chunks = []
    y_score_chunks = []
    total = 0
    n_images = 0

    for pred, gt, _ in iter_samples(dataset_root, anomaly_maps_root, subdataset):
        n_images += 1
        flat_pred = pred.reshape(-1)
        flat_gt = gt.reshape(-1)

        # sample pixels from this image
        remaining = max_pixels - total
        if remaining <= 0:
            break

        take = min(len(flat_pred), max(5000, remaining // 10))  # حداقل 5k از هر تصویر
        idx = rng.choice(len(flat_pred), size=take, replace=False)

        y_score_chunks.append(flat_pred[idx].astype(np.float32))
        y_true_chunks.append(flat_gt[idx].astype(np.uint8))
        total += take

    if n_images == 0:
        return np.nan, 0

    y_true = np.concatenate(y_true_chunks)
    y_score = np.concatenate(y_score_chunks)

    if len(np.unique(y_true)) < 2:
        return np.nan, n_images

    return float(roc_auc_score(y_true, y_score)), n_images

def au_pro_streaming(dataset_root: Path, anomaly_maps_root: Path, subdataset: str,
                     pro_limit=0.3, n_thresh=50, max_images=120, seed=42):
    """
    Memory-safe AU-PRO:
    - Uses subset of images (max_images)
    - Uses fewer thresholds (n_thresh)
    """
    rng = np.random.default_rng(seed)

    # collect list of available samples (paths only, not arrays)
    # (کم‌هزینه چون فقط مسیرها را نگه می‌داریم)
    samples = []
    test_dir = dataset_root / subdataset / "test"
    for defect in sorted([p.name for p in test_dir.iterdir() if p.is_dir()]):
        img_dir = test_dir / defect
        for img_path in sorted(img_dir.glob("*.*")):
            stem = img_path.stem
            pred_path = anomaly_maps_root / defect / f"{stem}.tiff"
            if not pred_path.exists():
                alt = anomaly_maps_root / defect / f"{stem}.tif"
                if alt.exists():
                    pred_path = alt
                else:
                    continue
            samples.append((pred_path, defect, stem))

    if len(samples) == 0:
        return np.nan, 0

    # subsample images
    if len(samples) > max_images:
        idx = rng.choice(len(samples), size=max_images, replace=False)
        samples = [samples[i] for i in idx]

    # find global min/max on subset for normalization
    mins, maxs = [], []
    for pred_path, _, _ in samples:
        pred = tifffile.imread(pred_path.as_posix()).astype(np.float32)
        if pred.ndim != 2:
            pred = pred.squeeze()
        mins.append(float(pred.min()))
        maxs.append(float(pred.max()))
    s_min, s_max = float(np.min(mins)), float(np.max(maxs))
    if s_max - s_min < 1e-12:
        return np.nan, len(samples)

    thresholds = np.linspace(0.0, 1.0, n_thresh, dtype=np.float32)
    fprs, pros = [], []

    gt_dir = dataset_root / subdataset / "ground_truth"

    for thr in thresholds:
        pro_vals = []
        fp = 0
        tn = 0

        for pred_path, defect, stem in samples:
            pred = tifffile.imread(pred_path.as_posix()).astype(np.float32)
            if pred.ndim != 2:
                pred = pred.squeeze()
            p = (pred - s_min) / (s_max - s_min + 1e-12)
            pred_bin = (p >= thr).astype(np.uint8)

            if defect == "good":
                gt = np.zeros(pred_bin.shape, dtype=np.uint8)
            else:
                mask_path = gt_dir / defect / f"{stem}_mask.png"
                gt = _load_mask(mask_path, pred_bin.shape)

            bg = (gt == 0)
            fp += int((pred_bin[bg] == 1).sum())
            tn += int((pred_bin[bg] == 0).sum())

            if gt.sum() == 0:
                continue

            cc = label(gt, connectivity=1)
            for rid in range(1, cc.max() + 1):
                region = (cc == rid)
                area = int(region.sum())
                if area == 0:
                    continue
                inter = int((pred_bin[region] == 1).sum())
                pro_vals.append(inter / (area + 1e-12))

        fpr = fp / (fp + tn + 1e-12)
        pro = float(np.mean(pro_vals)) if len(pro_vals) else 0.0
        fprs.append(fpr)
        pros.append(pro)

    fprs = np.array(fprs, dtype=np.float32)
    pros = np.array(pros, dtype=np.float32)

    order = np.argsort(fprs)
    fprs = fprs[order]
    pros = pros[order]

    m = fprs <= pro_limit
    if m.sum() < 2:
        return np.nan, len(samples)

    area = np.trapz(pros[m], fprs[m])
    au_pro = float(area / (pro_limit + 1e-12))
    return au_pro, len(samples)


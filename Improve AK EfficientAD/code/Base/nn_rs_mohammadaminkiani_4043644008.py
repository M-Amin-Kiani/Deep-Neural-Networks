def pixel_auroc_histogram(dataset_root: Path, maps_root: Path, subdataset: str, bins=4096):
    """
    Pixel AUROC using histogram accumulation (streaming).
    Computed ONLY on images with available GT mask.
    """
    smin, smax = None, None
    n_used_imgs = 0
    n_pos = 0
    n_neg = 0

    # pass 1: min/max + counts on GT-available images
    for defect, stem, pred, gt in iter_pred_gt(dataset_root, maps_root, subdataset):
        if gt is None:
            continue
        n_used_imgs += 1
        vmin, vmax = float(pred.min()), float(pred.max())
        smin = vmin if smin is None else min(smin, vmin)
        smax = vmax if smax is None else max(smax, vmax)
        n_pos += int((gt==1).sum())
        n_neg += int((gt==0).sum())

    if n_used_imgs == 0 or smin is None or (smax - smin) < 1e-12 or n_pos == 0 or n_neg == 0:
        return np.nan, n_used_imgs, n_pos, n_neg

    pos_hist = np.zeros(bins, dtype=np.int64)
    neg_hist = np.zeros(bins, dtype=np.int64)

    # pass 2: fill hist
    for defect, stem, pred, gt in iter_pred_gt(dataset_root, maps_root, subdataset):
        if gt is None:
            continue
        p = (pred - smin) / (smax - smin + 1e-12)
        p = np.clip(p, 0.0, 1.0)
        idx = np.minimum((p * (bins-1)).astype(np.int64), bins-1)

        pos_idx = idx[gt==1]
        neg_idx = idx[gt==0]
        if pos_idx.size:
            pos_hist += np.bincount(pos_idx, minlength=bins)
        if neg_idx.size:
            neg_hist += np.bincount(neg_idx, minlength=bins)

    pos_total = pos_hist.sum()
    neg_total = neg_hist.sum()
    if pos_total == 0 or neg_total == 0:
        return np.nan, n_used_imgs, int(pos_total), int(neg_total)

    # threshold from high to low
    tpr = np.cumsum(pos_hist[::-1]) / (pos_total + 1e-12)
    fpr = np.cumsum(neg_hist[::-1]) / (neg_total + 1e-12)

    auc = float(np.trapz(tpr, fpr))
    return auc, n_used_imgs, int(pos_total), int(neg_total)


def load_mask_any(mask_candidates, target_shape):
    """Load first existing mask path from candidates; resize to target if needed."""
    for mp in mask_candidates:
        mp = Path(mp)
        if mp.exists():
            m = np.array(Image.open(mp).convert("L"), dtype=np.uint8)
            m = (m > 0).astype(np.uint8)
            if m.shape != target_shape:
                m_img = Image.fromarray(m * 255).resize((target_shape[1], target_shape[0]), resample=Image.NEAREST)
                m = (np.array(m_img) > 0).astype(np.uint8)
            return m
    return np.zeros(target_shape, dtype=np.uint8)

def iter_pred_gt(dataset_root: Path, anomaly_maps_root: Path, subdataset: str, dataset_kind: str):
    """
    Yield (pred_map, gt_mask) one by one.
    dataset_kind: "mvtec_ad" or "mvtec_loco"
    """
    test_dir = dataset_root / subdataset / "test"
    gt_dir = dataset_root / subdataset / "ground_truth"

    for defect_dir in sorted([p for p in test_dir.iterdir() if p.is_dir()]):
        defect = defect_dir.name
        for img_path in sorted(defect_dir.glob("*.*")):
            stem = img_path.stem

            pred_path = anomaly_maps_root / defect / f"{stem}.tiff"
            if not pred_path.exists():
                alt = anomaly_maps_root / defect / f"{stem}.tif"
                if alt.exists():
                    pred_path = alt
                else:
                    continue

            pred = tifffile.imread(pred_path.as_posix()).astype(np.float32)
            if pred.ndim != 2:
                pred = pred.squeeze()

            if defect == "good":
                gt = np.zeros(pred.shape, dtype=np.uint8)
            else:
                # --- MVTec AD: <stem>_mask.png
                # --- LOCO: usually <stem>.png (and sometimes also *_mask.png) -> so we search both safely
                if dataset_kind == "mvtec_ad":
                    cands = [gt_dir / defect / f"{stem}_mask.png"]
                else:
                    cands = [
                        gt_dir / defect / f"{stem}.png",
                        gt_dir / defect / f"{stem}_mask.png",
                    ]
                    # extra robust: any png that starts with stem
                    cands += list((gt_dir / defect).glob(f"{stem}*.png"))

                gt = load_mask_any(cands, pred.shape)

            yield pred, gt

def pixel_auroc_stream(dataset_root: Path, anomaly_maps_root: Path, subdataset: str, dataset_kind: str,
                       max_pixels=3_000_000, seed=42):
    """
    Pixel AUROC with bounded RAM: random pixel sampling across images.
    This is standard & defensible when full pixel set is huge.
    """
    rng = np.random.default_rng(seed)
    y_true_chunks, y_score_chunks = [], []
    total = 0
    n_images = 0

    for pred, gt in iter_pred_gt(dataset_root, anomaly_maps_root, subdataset, dataset_kind):
        n_images += 1
        flat_pred = pred.reshape(-1)
        flat_gt = gt.reshape(-1)

        remaining = max_pixels - total
        if remaining <= 0:
            break

        take = min(len(flat_pred), max(20000, remaining // 8))  # حداقل 20k از هر تصویر
        idx = rng.choice(len(flat_pred), size=take, replace=False)

        y_score_chunks.append(flat_pred[idx].astype(np.float32))
        y_true_chunks.append(flat_gt[idx].astype(np.uint8))
        total += take

    if n_images == 0:
        return np.nan, 0

    y_true = np.concatenate(y_true_chunks)
    y_score = np.concatenate(y_score_chunks)

    if len(np.unique(y_true)) < 2:
        return np.nan, n_images

    return float(roc_auc_score(y_true, y_score)), n_images

def au_pro_stream_full(dataset_root: Path, anomaly_maps_root: Path, subdataset: str, dataset_kind: str,
                       pro_limit=0.3, n_thresh=100):
    """
    AU-PRO streaming (no RAM explosion):
    - 1) scan min/max
    - 2) thresholds loop and compute FPR/PRO sequentially
    """
    # --- 1) global min/max scan
    mins, maxs = [], []
    pairs = []
    for pred, gt in iter_pred_gt(dataset_root, anomaly_maps_root, subdataset, dataset_kind):
        mins.append(float(pred.min()))
        maxs.append(float(pred.max()))
        pairs.append((pred, gt))  # NOTE: still could be heavy if we keep all

    # To avoid keeping pairs in RAM, we re-iterate instead of storing.
    # So we won't use `pairs` at all:
    del pairs

    if len(mins) == 0:
        return np.nan, 0

    s_min, s_max = float(np.min(mins)), float(np.max(maxs))
    if s_max - s_min < 1e-12:
        return np.nan, len(mins)

    thresholds = np.linspace(0.0, 1.0, n_thresh, dtype=np.float32)
    fprs, pros = [], []

    # --- 2) compute curves
    n_images = 0
    for thr in thresholds:
        fp = 0
        tn = 0
        pro_vals = []

        # re-iterate without storing
        for pred, gt in iter_pred_gt(dataset_root, anomaly_maps_root, subdataset, dataset_kind):
            n_images += 1
            p = (pred - s_min) / (s_max - s_min + 1e-12)
            pred_bin = (p >= thr).astype(np.uint8)

            bg = (gt == 0)
            fp += int((pred_bin[bg] == 1).sum())
            tn += int((pred_bin[bg] == 0).sum())

            if gt.sum() == 0:
                continue

            cc = label(gt, connectivity=1)
            for rid in range(1, cc.max() + 1):
                region = (cc == rid)
                area = int(region.sum())
                if area == 0:
                    continue
                inter = int((pred_bin[region] == 1).sum())
                pro_vals.append(inter / (area + 1e-12))

        fpr = fp / (fp + tn + 1e-12)
        pro = float(np.mean(pro_vals)) if len(pro_vals) else 0.0
        fprs.append(fpr)
        pros.append(pro)

    fprs = np.array(fprs, dtype=np.float32)
    pros = np.array(pros, dtype=np.float32)

    order = np.argsort(fprs)
    fprs = fprs[order]
    pros = pros[order]

    m = fprs <= pro_limit
    if m.sum() < 2:
        return np.nan, len(mins)

    area = np.trapz(pros[m], fprs[m])
    au_pro = float(area / (pro_limit + 1e-12))
    return au_pro, len(mins)


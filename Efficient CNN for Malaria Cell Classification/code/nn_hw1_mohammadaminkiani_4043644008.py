def accuracy_from_probs(probs, y_true):
    preds = (probs >= 0.5).float()
    return (preds.eq(y_true).float().mean()).item()

def train_one_model(model, run_name, train_loader, test_loader, epochs=8, lr=1e-3):
    model = model.to(device)
    criterion = nn.BCELoss()
    optimizer = optim.RMSprop(model.parameters(), lr=lr)

    writer = SummaryWriter(log_dir=f"runs/{run_name}")

    global_step = 0
    for epoch in range(1, epochs+1):
        model.train()
        train_loss = 0.0
        train_acc = 0.0

        for x, y in train_loader:
            x, y = x.to(device), y.to(device)

            optimizer.zero_grad()
            probs = model(x)  # sigmoid output
            loss = criterion(probs, y)
            loss.backward()
            optimizer.step()

            train_loss += loss.item()
            train_acc += accuracy_from_probs(probs.detach(), y)

            writer.add_scalar("train/loss_step", loss.item(), global_step)
            global_step += 1

        train_loss /= len(train_loader)
        train_acc  /= len(train_loader)

        model.eval()
        test_loss = 0.0
        test_acc = 0.0
        with torch.no_grad():
            for x, y in test_loader:
                x, y = x.to(device), y.to(device)
                probs = model(x)
                loss = criterion(probs, y)
                test_loss += loss.item()
                test_acc  += accuracy_from_probs(probs, y)

        test_loss /= len(test_loader)
        test_acc  /= len(test_loader)

        writer.add_scalar("train/loss_epoch", train_loss, epoch)
        writer.add_scalar("train/acc_epoch", train_acc, epoch)
        writer.add_scalar("test/loss_epoch",  test_loss,  epoch)
        writer.add_scalar("test/acc_epoch",   test_acc,   epoch)

        print(f"[{run_name}] Epoch {epoch:02d}/{epochs} | "
              f"train loss {train_loss:.4f} acc {train_acc:.4f} | "
              f"test loss {test_loss:.4f} acc {test_acc:.4f}")

    writer.close()
    return model



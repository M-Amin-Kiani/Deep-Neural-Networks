class SpecialConv(nn.Module):
    """
    input:  (B,32,H,W)
    split -> (B,16,H,W) + (B,16,H,W)
    conv3x3 only on first 16 channels (16->16, pad=1) then concat back -> (B,32,H,W)
    """
    def __init__(self):
        super().__init__()
        self.conv16 = nn.Conv2d(16, 16, 3, 1, 1)

    def forward(self, x):
        x1, x2 = torch.split(x, 16, dim=1)
        y1 = self.conv16(x1)
        return torch.cat([y1, x2], dim=1)



class BaseCNN(nn.Module):
    # مطابق ساختار PDF: 4 Conv (k=3,pad=1,stride=1) + AdaptiveAvgPool2d + Linear + Sigmoid
    def __init__(self):
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(3, 16, kernel_size=3, stride=1, padding=1),
            nn.ReLU(inplace=True),

            nn.Conv2d(16, 16, kernel_size=3, stride=1, padding=1),
            nn.ReLU(inplace=True),

            nn.Conv2d(16, 32, kernel_size=3, stride=1, padding=1),
            nn.ReLU(inplace=True),

            nn.Conv2d(32, 32, kernel_size=3, stride=1, padding=1),
            nn.ReLU(inplace=True),
        )
        self.pool = nn.AdaptiveAvgPool2d((1,1))
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(32, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        x = self.features(x)
        x = self.pool(x)
        x = self.classifier(x)
        return x


class SpecialConv(nn.Module):
    """
    ورودی: (B,32,H,W)
    تقسیم به دو بخش 16 و 16
    اعمال Conv(16->16,k=3,pad=1) فقط روی نیمه اول
    کانکت نیمه دوم بدون تغییر
    خروجی: (B,32,H,W)
    """
    def __init__(self):
        super().__init__()
        self.conv16 = nn.Conv2d(16, 16, kernel_size=3, stride=1, padding=1)

    def forward(self, x):
        x1, x2 = torch.split(x, 16, dim=1)   # channel dim
        y1 = self.conv16(x1)
        y = torch.cat([y1, x2], dim=1)
        return y


class CNNWithSpecial(nn.Module):
    def __init__(self):
        super().__init__()
        self.pre = nn.Sequential(
            nn.Conv2d(3, 16, 3, 1, 1), nn.ReLU(inplace=True),
            nn.Conv2d(16,16, 3, 1, 1), nn.ReLU(inplace=True),
            nn.Conv2d(16,32, 3, 1, 1), nn.ReLU(inplace=True),
        )
        self.special = nn.Sequential(
            SpecialConv(),
            nn.ReLU(inplace=True)
        )
        self.pool = nn.AdaptiveAvgPool2d((1,1))
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(32, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        x = self.pre(x)
        x = self.special(x)
        x = self.pool(x)
        x = self.classifier(x)
        return x


class CNNWithSpecialAndPointwise(nn.Module):
    """
    بعد از لایه خاص، یک pointwise (1x1) می‌گذاریم تا mixing کانال‌ها بهتر شود.
    اینجا برای اینکه آزادی تنظیم داشته باشیم، 32->64 افزایش می‌دهیم و بعد classifier را مطابقش تغییر می‌دهیم.
    """
    def __init__(self):
        super().__init__()
        self.pre = nn.Sequential(
            nn.Conv2d(3, 16, 3, 1, 1), nn.ReLU(inplace=True),
            nn.Conv2d(16,16, 3, 1, 1), nn.ReLU(inplace=True),
            nn.Conv2d(16,32, 3, 1, 1), nn.ReLU(inplace=True),
        )
        self.special = nn.Sequential(
            SpecialConv(),
            nn.ReLU(inplace=True)
        )
        self.pointwise = nn.Sequential(
            nn.Conv2d(32, 64, kernel_size=1, stride=1, padding=0),
            nn.ReLU(inplace=True)
        )
        self.pool = nn.AdaptiveAvgPool2d((1,1))
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(64, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        x = self.pre(x)
        x = self.special(x)
        x = self.pointwise(x)
        x = self.pool(x)
        x = self.classifier(x)
        return x


